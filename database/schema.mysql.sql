-- PluQ-I initial shared-hosting schema.
-- Foundation only; not the complete production schema.

CREATE TABLE IF NOT EXISTS schema_migrations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 migration_name VARCHAR(190) NOT NULL UNIQUE,
 applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS admin_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('SUPER_ADMIN','ADMIN','OPERATOR') NOT NULL DEFAULT 'OPERATOR',
 status ENUM('ACTIVE','BLOCKED') NOT NULL DEFAULT 'ACTIVE',
 last_login_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS games (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 slug VARCHAR(150) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 description TEXT NULL,
 icon_url VARCHAR(500) NULL,
 status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
 sort_order INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_games_status_sort (status, sort_order, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS providers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(32) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL,
 status ENUM('ACTIVE','LOW_BALANCE','DISABLED','ERROR') NOT NULL DEFAULT 'ACTIVE',
 balance DECIMAL(18,2) NULL,
 balance_threshold DECIMAL(18,2) NOT NULL DEFAULT 100000,
 reserve_percentage DECIMAL(5,2) NOT NULL DEFAULT 50.00,
 last_balance_check_at DATETIME NULL,
 last_error TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 game_id BIGINT UNSIGNED NOT NULL,
 provider_id BIGINT UNSIGNED NOT NULL,
 provider_product_code VARCHAR(190) NOT NULL,
 name VARCHAR(190) NOT NULL,
 base_price DECIMAL(18,2) NOT NULL,
 selling_price DECIMAL(18,2) NOT NULL,
 status ENUM('ACTIVE','INACTIVE','OUT_OF_STOCK') NOT NULL DEFAULT 'ACTIVE',
 metadata JSON NULL,
 synced_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_provider_product (provider_id, provider_product_code),
 INDEX idx_products_catalog (game_id, status, selling_price),
 CONSTRAINT fk_products_game FOREIGN KEY (game_id) REFERENCES games(id),
 CONSTRAINT fk_products_provider FOREIGN KEY (provider_id) REFERENCES providers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(26) NOT NULL UNIQUE,
 game_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 provider_id BIGINT UNSIGNED NOT NULL,
 customer_email VARCHAR(255) NULL,
 customer_game_data JSON NOT NULL,
 base_price DECIMAL(18,2) NOT NULL,
 selling_price DECIMAL(18,2) NOT NULL,
 admin_fee DECIMAL(18,2) NOT NULL DEFAULT 0,
 payment_status ENUM('PENDING','PAID','FAILED','EXPIRED','REFUND_PENDING','REFUNDED') NOT NULL DEFAULT 'PENDING',
 order_status ENUM('PENDING','QUEUED','PROCESSING','RETRYING','SUCCESS','FAILED','REFUND_PENDING','REFUNDED','MANUAL_REVIEW') NOT NULL DEFAULT 'PENDING',
 supplier_reference VARCHAR(190) NULL,
 retry_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
 last_error TEXT NULL,
 paid_at DATETIME NULL,
 fulfilled_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_orders_queue (order_status, payment_status, created_at),
 INDEX idx_orders_created (created_at),
 CONSTRAINT fk_orders_game FOREIGN KEY (game_id) REFERENCES games(id),
 CONSTRAINT fk_orders_product FOREIGN KEY (product_id) REFERENCES products(id),
 CONSTRAINT fk_orders_provider FOREIGN KEY (provider_id) REFERENCES providers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment_transactions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 gateway VARCHAR(32) NOT NULL DEFAULT 'DUITKU',
 merchant_order_id VARCHAR(190) NOT NULL UNIQUE,
 gateway_reference VARCHAR(190) NULL,
 amount DECIMAL(18,2) NOT NULL,
 status ENUM('PENDING','PAID','FAILED','EXPIRED','REFUND_PENDING','REFUNDED') NOT NULL DEFAULT 'PENDING',
 callback_payload JSON NULL,
 callback_received_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_payment_status (status, created_at),
 CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS job_queue (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 job_type VARCHAR(80) NOT NULL,
 payload JSON NOT NULL,
 status ENUM('PENDING','PROCESSING','RETRY','DONE','FAILED') NOT NULL DEFAULT 'PENDING',
 attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
 available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 locked_at DATETIME NULL,
 lock_token CHAR(32) NULL,
 last_error TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_job_ready (status, available_at, id),
 INDEX idx_job_lock (status, locked_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor_type VARCHAR(32) NOT NULL,
 actor_id BIGINT UNSIGNED NULL,
 action VARCHAR(120) NOT NULL,
 entity_type VARCHAR(80) NULL,
 entity_id VARCHAR(100) NULL,
 details JSON NULL,
 ip_address VARCHAR(45) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_created (created_at),
 INDEX idx_audit_entity (entity_type, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

